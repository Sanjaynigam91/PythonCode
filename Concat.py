import pandas as pd

num1=pd.Series([1,2,3,4,5])
num2=pd.Series([6,7,8,9,10])

print("Merge two Series by using Concat")
result=pd.concat([num1,num2])
print(result)

print("Merge two Data frame by using Concat")
d1=pd.DataFrame({"Even1":[2,4,6,8,10],"Even2":[12,14,16,18,20]})
d2=pd.DataFrame({"Odd1":[1,3,5],"Odd2":[13,17,19]})
result1=pd.concat([d1,d2],axis=1)
print(result1)
print("Concat two Data frame by using outer join")
result2=pd.concat([d1,d2],axis=1,join="outer")
print(result2)
print("Concat two Data frame by using inner join")
result3=pd.concat([d1,d2],axis=1,join="inner")
print(result3)
print("Concat two Data frame by using keys")
d3=pd.DataFrame({"Even1":[2,4,6,8,10],"Even2":[12,14,16,18,20]})
d4=pd.DataFrame({"Odd1":[1,3,5,7,11],"Odd2":[13,17,19,23,29]})
result4=pd.concat([d3,d4],axis=1,keys=["key1","key2"])
print(result4)
print("Concat 1D and 2D Data frame")
d5=pd.DataFrame({"Even":[2,4,6,8,10]})
d6=pd.DataFrame({"Even1":[12,14,16,18,20],"Odd":[13,17,19,23,29]})
result5=pd.concat([d5,d6],axis=1,keys=["key1","key2"])
print(result5)